-- ============================================================================
-- 009 シミュレーション強化
-- ============================================================================
-- 目的:
--   (A) 発災からの経過時間を全参加者で共有してタイマー演出する
--   (B) 災害イベント(余震・停電・けが人・物資到着など)を本部から
--       発火し、共有タイムラインで全員に通知する
--
-- 安全性:
--   - 新規列追加は NULL 許容で既存行・既存コードを壊さない
--   - CHECK 拡張は VALUES を 'event' 追加するだけで後方互換
--   - 2回流しても壊れない(IF NOT EXISTS / DROP & CREATE)
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1. sessions に simulated_start_at(発災開始時刻)を追加
-- ----------------------------------------------------------------------------
-- WHY: 訓練の「発災時刻」を全参加者で共有することで、
--      「発災から ◯分」の経過表示と各ステップの目安時間管理ができる。
--      NULL のときは「未開始」(従来通り無時間で動く)。
ALTER TABLE public.sessions
  ADD COLUMN IF NOT EXISTS simulated_start_at TIMESTAMPTZ;


-- ----------------------------------------------------------------------------
-- 2. shared_posts.type に 'event'(災害イベント)を追加
-- ----------------------------------------------------------------------------
-- WHY: 共有タイムラインに「困った/発見」と並んで「災害イベント」を
--      表示できるようにする。本部が訓練中に発火する「余震」「停電」等。
--      type を分けるのは finish 画面の集計で『困った』にカウントしない
--      ためと、表示色を分けるため。
DO $$
BEGIN
  -- 既存の CHECK 制約を一度落とす(名前を取得)
  ALTER TABLE public.shared_posts DROP CONSTRAINT IF EXISTS shared_posts_type_check;
  -- 新しい CHECK 制約を追加
  ALTER TABLE public.shared_posts
    ADD CONSTRAINT shared_posts_type_check
    CHECK (type IN ('trouble', 'finding', 'event'));
END $$;
